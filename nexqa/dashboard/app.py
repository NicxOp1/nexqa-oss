"""
NEXQA v1.0 — Dashboard

Run with: `streamlit run nexqa/dashboard/app.py`
Requires API running at http://localhost:8000
"""

import streamlit as st
import requests

API_URL = "http://localhost:8000"

st.set_page_config(
    page_title="NEXQA Dashboard",
    page_icon="🧬",
    layout="wide",
)

st.title("🧬 NEXQA Voice AI Optimization")

# ── Sidebar ─────────────────────────────────────────────────────────

st.sidebar.header("Control Panel")
api_status = "🔴 Offline"
try:
    resp = requests.get(f"{API_URL}/health", timeout=2)
    if resp.status_code == 200:
        api_status = "🟢 Online"
except:
    pass
st.sidebar.text(f"API Backend: {api_status}")

if api_status == "🔴 Offline":
    st.error("Please start the API backend: `uvicorn nexqa.api.server:app --reload`")
    st.stop()

# ── Tabs ────────────────────────────────────────────────────────────

tab_agents, tab_runs, tab_human = st.tabs(["🤖 Agents & Prompts", "🚀 QA Runs", "🧑‍💻 Human QA"])

# ── Tab 1: Agents ───────────────────────────────────────────────────

with tab_agents:
    st.header("Agent Management")
    
    try:
        agents = requests.get(f"{API_URL}/agents").json()
        agent_options = {f"{a['agent_name']} ({a['agent_id']})": a['agent_id'] for a in agents}
        
        selected_label = st.selectbox("Select Agent", options=list(agent_options.keys()))
        if selected_label:
            agent_id = agent_options[selected_label]
            
            col1, col2 = st.columns([1, 2])
            
            with col1:
                st.subheader("Details")
                agent_data = requests.get(f"{API_URL}/agents/{agent_id}").json()
                st.json(agent_data, expanded=False)
                
            with col2:
                st.subheader("Prompt Genome")
                try:
                    prompt_data = requests.get(f"{API_URL}/agents/{agent_id}/prompt").json()
                    genes = prompt_data.get("genes", [])
                    
                    for gene in genes:
                        with st.expander(f"{gene['type']} (Priority: {gene['priority']})"):
                            st.code(gene['content'], language="xml")
                            st.caption(f"Immutable: {gene['immutable']} | Max Mutations: {gene['max_mutations']}")
                except Exception as e:
                    st.error(f"Could not load genes: {e}")

    except Exception as e:
        st.error(f"Failed to fetch agents: {e}")

# ── Tab 2: QA Runs ──────────────────────────────────────────────────

with tab_runs:
    st.header("QA Run History")
    
    # Placeholder: fetch runs from Airtable or local logs?
    # For v1.0, we might just trigger new runs here.
    
    with st.form("new_run"):
        st.subheader("Start New Optimization Loop")
        run_agent_id = st.text_input("Agent ID", value=agent_id if 'agent_id' in locals() else "")
        spec_path = st.text_input("Spec Path", value="tests/specs/outbound_sales.yaml")
        submitted = st.form_submit_button("🚀 Launch Run")
        
        if submitted:
            try:
                res = requests.post(f"{API_URL}/runs/", params={"agent_id": run_agent_id, "spec_path": spec_path})
                if res.status_code == 200:
                    st.success(f"Run started! ID: {res.json()['run_id']}")
                else:
                    st.error(f"Failed: {res.text}")
            except Exception as e:
                st.error(f"Error: {e}")

# ── Tab 3: Human QA ─────────────────────────────────────────────────

with tab_human:
    st.header("Human Verification")
    
    st.info("Start a manual testing session generated by NEXQA.")
    
    tester_name = st.text_input("Tester Name", "QA Engineer")
    if st.button("Start Sesssion"):
        # Create session via API
        try:
            res = requests.post(f"{API_URL}/human-qa/session", params={"agent_id": agent_id, "tester_name": tester_name})
            session = res.json()
            st.session_state['active_session'] = session
            st.success(f"Session {session['session_id']} started!")
        except Exception as e:
            st.error(f"Failed: {e}")
            
    if 'active_session' in st.session_state:
        session = st.session_state['active_session']
        st.subheader(f"Session: {session['session_id']}")
        
        # Fetch scripts
        scripts = requests.get(f"{API_URL}/human-qa/session/{session['session_id']}/scripts").json()
        
        for script in scripts:
            st.markdown(f"### {script['scenario_name']}")
            for step in script['steps']:
                st.markdown(f"**{step['type'].upper()}**: {step['instruction']}")
                if step['criteria']:
                    st.info(f"Criteria: {step['criteria']}")
            
            # Result input
            passed = st.checkbox("Passed?", key=f"pass_{script['scenario_id']}")
            notes = st.text_area("Notes/Issues", key=f"notes_{script['scenario_id']}")
            
            if st.button(f"Submit {script['scenario_name']}", key=f"sub_{script['scenario_id']}"):
                # Post result
                result_payload = {
                    "script_id": script['scenario_id'],
                    "passed": passed,
                    "notes": notes,
                    "issues_found": []
                }
                requests.post(f"{API_URL}/human-qa/session/{session['session_id']}/result", json=result_payload)
                st.success("Result submitted!")

